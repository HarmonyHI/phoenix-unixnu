#!/bin/bash
#
# Build phoenix UEFI, embed the payload FAT into the firmware, and package a
# fastboot boot image.
#
#   ./Resources/Scripts/build-phoenix.sh [output.img]
#
# Two firmware passes are needed: the first produces the payload applications
# (ADTInspector, HelloPayload), which are then packed into the payload FAT that
# the second pass compresses into the FV.
#
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"

OUT="${1:-Mu-phoenix-payload.img}"
FAT="Platforms/Xiaomi/phoenixPkg/Payload/payload.fat"
PORT_DIR="${PHOENIX_PORT_DIR:-$ROOT/../UniXNU-phoenix-main}"

export PATH="$ROOT/Mu_Basecore/BaseTools/BinWrappers/PosixLike:/opt/homebrew/Cellar/llvm@18/18.1.8/bin:/opt/homebrew/opt/lld/bin:/opt/homebrew/bin:$PATH"
export EDK_TOOLS_BIN="$ROOT/Mu_Basecore/BaseTools"
export WORKSPACE="$ROOT"
# Post-build symbol flattening deletes stale PDBs, which hosts with a delete
# guard abort on after a successful compile. Symbols are not needed here.
export EDK2_SKIP_FLATTEN_PDBS=1

build () {
  echo "=== firmware build ($1) ==="
  python3 build_uefi.py -d phoenix -r DEBUG 2>&1 | tail -2
}

find_efi () {
  find Build/phoenixPkg/DEBUG_CLANGPDB -path "*$1*" -name "$1.efi" | head -1 || true
}

build "pass 1: modules"

ADD=()

ADT_INSPECTOR="$(find_efi ADTInspector)"
if [ -n "$ADT_INSPECTOR" ]; then
  echo "payload: $ADT_INSPECTOR"
  ADD+=(--add "Payloads/ADTInspector.efi=$ADT_INSPECTOR")
else
  echo "warning: ADTInspector.efi not found" >&2
fi

HELLO="$(find_efi HelloPayload)"
if [ -n "$HELLO" ]; then
  echo "payload: $HELLO"
  ADD+=(--add "Payloads/HelloPayload.efi=$HELLO")
else
  echo "warning: HelloPayload.efi not found" >&2
fi

#
# The ADT is generated by the port tree, which lives next to this repository.
# When it is absent the payload simply ships without an ADT; the inspector then
# reports the missing file instead of failing silently.
#
ADT_TOOL="$PORT_DIR/scripts/make-phoenix-adt.py"
ADT_OUT="Platforms/Xiaomi/phoenixPkg/Payload/phoenix.adt"
if [ -f "$ADT_TOOL" ]; then
  mkdir -p "$(dirname "$ADT_OUT")"
  python3 "$ADT_TOOL" --output "$ADT_OUT"
  python3 "$PORT_DIR/scripts/check-phoenix-adt.py" "$ADT_OUT" | tail -1
  ADD+=(--add "phoenix.adt=$ADT_OUT")
else
  echo "warning: $ADT_TOOL not found, payload will not carry an ADT" >&2
fi

python3 Resources/Scripts/mkfat.py "$FAT" "${ADD[@]}"
python3 Resources/Scripts/checkfat.py "$FAT" "EFI/UniXNU/unixnu.toml" | tail -2
if command -v fsck_msdos >/dev/null 2>&1; then
  fsck_msdos -n "$FAT" 2>&1 | tail -2
fi

build "pass 2: embed payload"

RS="$ROOT/Resources/Scripts/mkinitrd.sh"
"$RS" "$OUT"
